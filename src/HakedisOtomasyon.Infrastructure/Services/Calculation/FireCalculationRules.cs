{
    private readonly IPriceListService _priceListService;
    private readonly IDisciplineProfileService _disciplineProfiles;
    private readonly ILogger<FireCalculationRules> _logger;

    public MechanicalDiscipline Discipline => MechanicalDiscipline.Fire;

    // Sülyen/Polisan fiyat kalemleri — bir kerelik yüklenir, sonraki çağrılarda önbellekten kullanılır.
    private PriceItemDto? _sulyenSmallPriceItem;
    private PriceItemDto? _sulyenMediumPriceItem;
    private PriceItemDto? _sulyenLargePriceItem;
    private bool _sulyenPricesCached;
