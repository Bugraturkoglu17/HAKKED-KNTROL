    /// <summary>
    /// Parses the inch diameter from a normalized pipe description.
    /// Fractional sizes are checked first to prevent false single-digit matches.
    /// </summary>
    private static decimal? ExtractPipeDiameter(string nrmPipeStr)
    {
        var s = nrmPipeStr;
        if (s.Contains("2 1/2")) return 2.5m;
        if (s.Contains("1 1/4")) return 1.25m;
        if (s.Contains("1 1/2")) return 1.5m;
        if (s.Contains("3/4"))   return 0.75m;
        if (s.Contains("1/2"))   return 0.5m;
        if (PipeSizeMatch(s, "10")) return 10m;
        if (PipeSizeMatch(s, "8"))  return 8m;
        if (PipeSizeMatch(s, "6"))  return 6m;
        if (PipeSizeMatch(s, "5"))  return 5m;
        if (PipeSizeMatch(s, "4"))  return 4m;
        if (PipeSizeMatch(s, "3"))  return 3m;
        if (PipeSizeMatch(s, "2"))  return 2m;
        if (PipeSizeMatch(s, "1"))  return 1m;
        return null;
    }

    private static bool PipeSizeMatch(string s, string digit)
    {
        if (s.Contains(digit + "\"")) return true;
        if (s.Contains(digit + " \"")) return true;
        if (s.Contains(digit + " INC")) return true;
        int idx = -1;
        while ((idx = s.IndexOf(digit, idx + 1)) >= 0)
        {
            bool prevOk = idx == 0 || (!char.IsDigit(s[idx - 1]) && s[idx - 1] != '/');
            if (!prevOk) continue;
            int after = idx + digit.Length;
            bool nextOk = after >= s.Length || (!char.IsDigit(s[after]) && s[after] != '/');
            if (nextOk) return true;
        }
        return false;
    }

