    internal static string Nrm(string s) =>
        s.Replace('ı', 'I').Replace('İ', 'I')
         .Replace('ğ', 'G').Replace('Ğ', 'G')
         .Replace('ü', 'U').Replace('Ü', 'U')
         .Replace('ş', 'S').Replace('Ş', 'S')
         .Replace('ö', 'O').Replace('Ö', 'O')
         .Replace('ç', 'C').Replace('Ç', 'C')
         .ToUpperInvariant().Trim();

    private static string NrmPipe(string s)
    {
        return Nrm(s)
            .Replace('“', '"').Replace('”', '"')
            .Replace('″', '"').Replace('ʺ', '"')
            .Replace('＂', '"')
            .Replace("½", " 1/2").Replace("¼", " 1/4")
            .Replace("2-1/2", "2 1/2")
            .Replace("1-1/4", "1 1/4")
            .Replace("1-1/2", "1 1/2")
            .Replace("21/2", "2 1/2")
            .Replace("11/4", "1 1/4")
            .Replace("11/2", "1 1/2");
    }
