    private static string GenerateFlexivaExportDescription(PriceItemDto item)
    {
        const decimal discountRate = 0.30m;
        var discountedPrice = item.MaterialPrice;
        var originalPrice   = discountRate < 1 ? discountedPrice / (1 - discountRate) : discountedPrice;

        var unit = (item.Unit ?? "m").Trim();
        decimal unitQty  = 1;
        string  baseUnit = unit;
        var parts = unit.Split(' ', StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length >= 2 &&
            decimal.TryParse(parts[0], System.Globalization.NumberStyles.Number,
                System.Globalization.CultureInfo.InvariantCulture, out var q))
        {
            unitQty  = q;
            baseUnit = parts[1];
        }

        var trCulture = new System.Globalization.CultureInfo("tr-TR");
        var perUnitPrice = unitQty > 0 ? discountedPrice / unitQty : discountedPrice;
        return $"{item.Description} {originalPrice.ToString("N2", trCulture)} TL x %30 iskonto = {discountedPrice.ToString("N2", trCulture)} TL / {unit} = {perUnitPrice.ToString("N2", trCulture)} TL/{baseUnit}";
    }

