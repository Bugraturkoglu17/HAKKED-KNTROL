    public string? ResolveSectionName(string description, string? autoGeneratedType, bool isInvoiceBased)
    {
        if (isInvoiceBased || autoGeneratedType == "InvoicePlus10" || Nrm(description).Contains("FATURA +%10"))
            return "DİĞER";

        if (!string.IsNullOrEmpty(autoGeneratedType))
        {
            if (autoGeneratedType is "GalvanizedDuctFitting30" or "InsulationMounting")
                return "HAVALANDIRMA";
            if (autoGeneratedType is "BlackPipeFitting30" or "BlackPipeFitting80" or
                "SiyahBoruFittings30" or "SiyahBoruFittings80" or "GalvanizedSteelPipeFitting40" or
                "BlackSteelPipeRedOxidePaint" or "BlackSteelPipePolisanPaint")
                return "YANGIN";
        }

        if (IsHvacDesc(description)) return "HAVALANDIRMA";
        if (IsFireDesc(description)) return "YANGIN";

        // Fiyat listesi ürünleri varsayılan olarak yangın tesisatı sayılır.
        return "YANGIN";
    }

    public bool ShouldIncludeReferenceTable(string description, string tableKey)
    {
        var s = Nrm(description);
        return tableKey.ToUpperInvariant() switch
        {
            "FLEXIVA" => IsFlexivaDesc(description),
            "BDKF"    => s.Contains("BDKF"),
            "BDTX"    => s.Contains("BDTX"),
            _         => false
        };
    }

