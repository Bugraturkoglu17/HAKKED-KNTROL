    private static bool IsGalvanizedDuctFittingRequired(PriceItemDto item)
    {
        var mainCat = Nrm(item.MainCategory ?? "");
        var desc    = Nrm(item.Description);
        var inv     = Nrm(item.InvoiceDescription ?? "");

        bool hasGalvanizKanal =
            (mainCat.Contains("GALVANIZ") && mainCat.Contains("KANAL")) ||
            (desc.Contains("GALVANIZ")    && desc.Contains("KANAL"))    ||
            (inv.Contains("GALVANIZ")     && inv.Contains("KANAL"));
        if (!hasGalvanizKanal) return false;

        var combined = $"{desc} {inv}";

        if (combined.Contains("0.5 MM") || combined.Contains("0.5MM") ||
            combined.Contains("0,5 MM") || combined.Contains("0,5MM") ||
            combined.Contains("0.6 MM") || combined.Contains("0.6MM") ||
            combined.Contains("0,6 MM") || combined.Contains("0,6MM") ||
            combined.Contains("0.8 MM") || combined.Contains("0.8MM") ||
            combined.Contains("0,8 MM") || combined.Contains("0,8MM") ||
            combined.Contains("1.0 MM") || combined.Contains("1.0MM") ||
            combined.Contains("1,0 MM") || combined.Contains("1,0MM"))
            return true;

        return combined.Contains("<= 250")  || combined.Contains("<=250")  ||
               combined.Contains("<= 499")  || combined.Contains("<=499")  ||
               combined.Contains("<= 500")  || combined.Contains("<=500")  ||
               combined.Contains("<= 990")  || combined.Contains("<=990")  ||
               combined.Contains("<= 1490") || combined.Contains("<=1490") ||
               combined.Contains("EBAD <=5") || combined.Contains("EBAD<=5") ||
               combined.Contains("EBADI <=5") || combined.Contains("EBADI<=5");
    }

    private static bool IsGalvanizedDuctFittingFromDesc(string desc)
    {
        var s = Nrm(desc);
        if (!(s.Contains("GALVANIZ") && s.Contains("KANAL"))) return false;
        return s.Contains("0.5 MM") || s.Contains("0.5MM") ||
               s.Contains("0,5 MM") || s.Contains("0,5MM") ||
