/// <summary>
/// Yangın disiplinine özel otomatik kalem üretme ve Excel sınıflandırma kuralları.
/// Bu sınıf, eskiden ServiceItemGrid.razor ve ExcelExportService.cs içine dağılmış olan
/// fittings/boya/izolasyon/BDKF/BDTX/Flexiva mantığının TAŞINDIĞI tek merkezi yerdir.
/// Mevcut davranış birebir korunmuştur — sadece konum ve çağrı şekli değişmiştir.
